<h1>Nebelseetal, das Fantasy-Browsergame</h1>
<h2>- Community</h2>
<br/><br/>
<p class="textblock">
Nebelseetal bietet Dir im Spiel umfangreiche Communityfunktionen. Du kannst Dir Dein eigenes, individuelles Herrscherprofil anlegen, in dem Du Dich oder den Charakter den Du spielst und dein Volk beschreiben kannst. Dieses Profil kann von anderen Spielern eingesehen werden.
<br/><br/>
Du kannst B&uuml;ndnisse mit einzelnen Spielern schlie&szlig;en. Du siehst, wenn deine B&uuml;ndnispartner online sind und das versenden von Einheiten und Nachrichten ist zu B&uuml;ndnispartnern hin komfortabler.
<br/><br/>
Mehrere Spieler k&ouml;nnen sich zu einer Gilde zusammenschlie&szlig;en. Gilden haben im Spiel eine eigene Rangwertung, die sich nach den Punkten der Gildenmitglieder richtet. Au&szlig;erdem k&ouml;nnen R&auml;nge innerhalb der Gilde vergeben und ein Gildenprofil angelegt werden, welches von den anderen Spielern einsehbar ist.
<br/><br/>
Neben den Ingamefunktionen bietet Nebelseetal noch das <a href="http://web.archive.org/web/20070911105233/http://forum.nebelseetal.de/" class="link" target="_blank">Nebelseetal Forum</a>, einen <a href="ts.php" class="link">Teamspeakserver</a> und einen <a href="chat.php" class="link">IRC-Channel</a> an. Um im IRC-Channel &uuml;ber diese Internetseite zugreifen zu k&ouml;nnen ben&ouml;tigt ihr ein Java-Plugin f&uuml;r Euren Browser. Dieses k&ouml;nnt ihr bei <a href="http://web.archive.org/web/20070911105233/http://java.com/de/" target="_blank" class="link">http://java.com/</a> kostenlos herunterladen.
