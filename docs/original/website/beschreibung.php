<p class="normaltext">
In Nebelseetal Online schlüpft ihr in die Rolle des Herrschers eines mittelalterlichen 
Reiches und müsst euer 
Geschick in Wirtschaft, Handel und Krieg unter Beweis stellen. Ihr startet das 
Spiel mit einer Siedlung und ein paar Rohstoffen. <br><br>

Zunächst gilt es die Rohstoffproduktion eurer Siedlung zu erhöhen indem ihr 
Holzfällerhütten, Steinmetze, Farmen usw. errichtet. Die so gewonnenen Rohstoffe 
können genutzt werden um weitere Gebäude zu errichten, Forschung zu betreiben oder 
Waffen und Rüstungen für eure Armee zu bauen. <br><br>

Das Spiel läuft in Echtzeit, was bedeutet, das Rohstoffproduktionen, 
Einheitenbewegungen, Forschungen etc. nicht in Runden ablaufen, sondern eine 
gewisse Zeit benötigen und dann abgeschlossen sind. Wenn ihr z.B. durch eine 
Holzfällerhütte 2 Holz/Stunde Produziert, dann bekommt eure Siedlung alle 30 
Minuten 1 Holz gutgeschrieben. Eine Forschung die 2 Tage, 10 Stunden dauert, 
ist auch erst nach 2 Tagen, 10 Stunden, nachdem ihr sie in Auftrag gegeben habt, 
abgeschlossen. <br><br>

Bevor ihr neue Produktionsstätten wie Schmiede, Bogenbauer oder Nähstube bauen 
könnt, müsst ihr gewisse Vorraussetzungen erforschen. Hierzu errichtet ihr eine 
Bibliothek. In ihr können eure Gelehrten ihre Studien treiben. Je weiter ihr 
eure Bibliothek ausbaut, desto komplexere Themen können sie in Angriff nehmen. 
Die Forschungen wie Schmiedkunst oder Landwirtschaft sind zum Teil Vorraussetzungen 
für Gebäude, Einheiten und andere Forschungen, erhöhen aber zum anderen Teil 
auch die Produktivität eurer Siedlungen.<br><br>

Wenn ihr genug Rohstoffe angesammelt habt könnt ihr damit beginnen auf eurer Welt 
neues Land zu erschließen und neue Siedlungen zu gründen. Auf jeder Welt in 
Nebelseetal-Online gibt es ein Magisches Portal, welches eure Welt mit vielen 
weiteren Welten verbindet. Dies sind die Welten von anderen Spielern, die dort 
ihrerseits Siedlungen errichtet haben. <br><br>

Habt ihr die Verbindung zu anderen Spielern hergestellt könnt ihr mit ihnen handeln, 
sie ausspionieren oder versuchen, sie mit euren Truppen zu überfallen und ihre 
Rohstoffe zu rauben.<br><br>

Auch könnt ihr mit anderen Spielern eine Gilde gründen, um gemeinsam gegen stärkere 
Tyrannen vorzugehen, organisiert Handelswaren herzustellen und zu verkaufen oder 
selbst Angst und Schrecken zu verbreiten.<br><br>

In Nebelseetal-Online stehen euch viele Wege offen, versucht euch einfach mal als 
Herrscher in einer fantastischen Welt voller Magie und Gefahren...

